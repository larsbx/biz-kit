REVOKE ALL ON FUNCTION agent_ops.claim_attempt(text,bigint,text,bytea,bigint,integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION agent_ops.renew_attempt(text,bigint,bigint,bytea,bigint) FROM PUBLIC;
REVOKE ALL ON FUNCTION agent_ops.attach_backend(text,bigint,bigint,bytea,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION agent_ops.record_candidate(text,bigint,bigint,bytea,bytea) FROM PUBLIC;
REVOKE ALL ON FUNCTION agent_ops.request_cancel(text,bigint) FROM PUBLIC;
REVOKE ALL ON FUNCTION agent_ops.confirm_cancel_preverified(text,bigint,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION agent_ops.reconcile_absent_preverified(text,bigint,bigint,text) FROM PUBLIC;

COMMIT;
