-- Engine-independent persistence primitives for AgentCore operational effects.
-- Must be installed in the existing biz-kit PostgreSQL database with a
-- reviewed migration. Neither this schema nor these functions authenticate
-- an agent, approve a signed TaskCore intent, or authorize business writes.
--
-- All functions are SECURITY INVOKER and explicitly withdrawn from PUBLIC.
-- Grant EXECUTE only to the host coordinator service DB role, never to agent
-- sandboxes or user-facing roles. The host MUST check current ledger grants,
-- read rights, tenant scope and profile approval before invoking them.
--
-- All time checks use the authoritative PostgreSQL clock. Lease tokens are
-- strong random secrets generated by the host; ONLY SHA-256 digests of tokens
-- are stored here. No plaintext token is persisted.
--
-- A timed-out lease remains leased until the host proves its backend outcome.
-- The reconcile_absent_preverified function cannot itself verify proof:
-- only a trusted host may call it AFTER independent verification.

BEGIN;

CREATE OR REPLACE FUNCTION agent_ops.claim_attempt(
  p_effect text,
  p_expected_version bigint,
  p_owner text,
  p_token_sha256 bytea,
  p_lease_ms bigint,
  p_attempt_limit integer
)
RETURNS TABLE (epoch bigint, version bigint)
LANGUAGE sql VOLATILE SECURITY INVOKER
AS $function$
  UPDATE agent_ops.execution_attempts AS a
     SET phase = 'leased',
         attempt_epoch = a.attempt_epoch + 1,
         attempts = a.attempts + 1,
         lease_owner = p_owner,
         lease_token_sha256 = p_token_sha256,
         lease_expires_at = clock_timestamp() + p_lease_ms * interval '1 millisecond',
         backend_ref = NULL,
         row_version = a.row_version + 1,
         updated_at = clock_timestamp()
   WHERE a.effect_id = p_effect
     AND a.row_version = p_expected_version
     AND a.phase = 'pending'
     AND a.attempts < p_attempt_limit
     AND p_attempt_limit BETWEEN 1 AND 10
     AND p_expected_version >= 1
     AND p_lease_ms BETWEEN 1 AND 300000
     AND p_owner ~ '^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$'
     AND octet_length(p_token_sha256) = 32
  RETURNING a.attempt_epoch, a.row_version;
$function$;

CREATE OR REPLACE FUNCTION agent_ops.renew_attempt(
  p_effect text,
  p_expected_version bigint,
  p_epoch bigint,
  p_token_sha256 bytea,
  p_lease_ms bigint
)
RETURNS TABLE (version bigint, expires_at timestamptz)
LANGUAGE sql VOLATILE SECURITY INVOKER
AS $function$
  UPDATE agent_ops.execution_attempts AS a
     SET lease_expires_at = GREATEST(
           a.lease_expires_at,
           clock_timestamp() + p_lease_ms * interval '1 millisecond'
         ),
         row_version = a.row_version + 1,
         updated_at = clock_timestamp()
   WHERE a.effect_id = p_effect
     AND a.row_version = p_expected_version
     AND a.attempt_epoch = p_epoch
     AND a.lease_token_sha256 = p_token_sha256
     AND a.phase = 'leased'
     AND a.lease_expires_at > clock_timestamp()
     AND p_lease_ms BETWEEN 1 AND 300000
     AND octet_length(p_token_sha256) = 32
  RETURNING a.row_version, a.lease_expires_at;
$function$;

CREATE OR REPLACE FUNCTION agent_ops.attach_backend(
  p_effect text,
  p_expected_version bigint,
  p_epoch bigint,
  p_token_sha256 bytea,
  p_backend_ref text
)
RETURNS TABLE (version bigint)
LANGUAGE sql VOLATILE SECURITY INVOKER
AS $function$
  UPDATE agent_ops.execution_attempts AS a
     SET backend_ref = p_backend_ref,
         row_version = a.row_version + 1,
         updated_at = clock_timestamp()
   WHERE a.effect_id = p_effect
     AND a.row_version = p_expected_version
     AND a.attempt_epoch = p_epoch
     AND a.lease_token_sha256 = p_token_sha256
     AND a.phase = 'leased'
     AND a.lease_expires_at > clock_timestamp()
     AND (a.backend_ref IS NULL OR a.backend_ref = p_backend_ref)
     AND p_backend_ref ~ '^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$'
     AND octet_length(p_token_sha256) = 32
  RETURNING a.row_version;
$function$;

CREATE OR REPLACE FUNCTION agent_ops.record_candidate(
  p_effect text,
  p_expected_version bigint,
  p_epoch bigint,
  p_token_sha256 bytea,
  p_candidate_digest bytea
)
RETURNS TABLE (version bigint)
LANGUAGE sql VOLATILE SECURITY INVOKER
AS $function$
  UPDATE agent_ops.execution_attempts AS a
     SET phase = 'candidate_ready',
         candidate_digest = p_candidate_digest,
         lease_owner = NULL,
         lease_token_sha256 = NULL,
         lease_expires_at = NULL,
         row_version = a.row_version + 1,
         updated_at = clock_timestamp()
   WHERE a.effect_id = p_effect
     AND a.row_version = p_expected_version
     AND a.attempt_epoch = p_epoch
     AND a.lease_token_sha256 = p_token_sha256
     AND a.phase = 'leased'
     AND a.lease_expires_at > clock_timestamp()
     AND octet_length(p_candidate_digest) = 32
     AND octet_length(p_token_sha256) = 32
  RETURNING a.row_version;
$function$;

CREATE OR REPLACE FUNCTION agent_ops.request_cancel(
  p_effect text,
  p_expected_version bigint
)
RETURNS TABLE (version bigint)
LANGUAGE sql VOLATILE SECURITY INVOKER
AS $function$
  UPDATE agent_ops.execution_attempts AS a
     SET phase = 'cancel_requested',
         attempt_epoch = a.attempt_epoch + 1,
         lease_owner = NULL,
         lease_token_sha256 = NULL,
         lease_expires_at = NULL,
         row_version = a.row_version + 1,
         updated_at = clock_timestamp()
   WHERE a.effect_id = p_effect
     AND a.row_version = p_expected_version
     AND a.phase IN ('pending', 'leased', 'candidate_ready')
  RETURNING a.row_version;
$function$;

CREATE OR REPLACE FUNCTION agent_ops.confirm_cancel_preverified(
  p_effect text,
  p_expected_version bigint,
  p_receipt_id text
)
RETURNS TABLE (version bigint)
LANGUAGE sql VOLATILE SECURITY INVOKER
AS $function$
  UPDATE agent_ops.execution_attempts AS a
     SET phase = 'cancelled',
         cancellation_receipt_id = p_receipt_id,
         row_version = a.row_version + 1,
         updated_at = clock_timestamp()
   WHERE a.effect_id = p_effect
     AND a.row_version = p_expected_version
     AND a.phase = 'cancel_requested'
     AND p_receipt_id ~ '^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$'
  RETURNING a.row_version;
$function$;

CREATE OR REPLACE FUNCTION agent_ops.reconcile_absent_preverified(
  p_effect text,
  p_expected_version bigint,
  p_epoch bigint,
  p_reconciliation_receipt_id text
)
RETURNS TABLE (version bigint)
LANGUAGE sql VOLATILE SECURITY INVOKER
AS $function$
  UPDATE agent_ops.execution_attempts AS a
     SET phase = 'pending',
         lease_owner = NULL,
         lease_token_sha256 = NULL,
         lease_expires_at = NULL,
         reconciliation_receipt_id = p_reconciliation_receipt_id,
         row_version = a.row_version + 1,
         updated_at = clock_timestamp()
   WHERE a.effect_id = p_effect
     AND a.row_version = p_expected_version
     AND a.attempt_epoch = p_epoch
     AND a.phase = 'leased'
     AND a.lease_expires_at <= clock_timestamp()
     AND p_reconciliation_receipt_id ~ '^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$'
  RETURNING a.row_version;
$function$;

-- PL/pgSQL functions are executable by PUBLIC by default. Revoke them
