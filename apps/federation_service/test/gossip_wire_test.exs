defmodule FederationService.GossipWireTest do
  use ExUnit.Case, async: true
  alias FederationService.{Gossip, GossipLease, GossipSync, Store}
  import FederationService.TestHelpers
  @alpha "https://alpha.example/actors/shop"
  @beta "https://beta.example/actors/shop"
  @reference Path.join(__DIR__, "support/gossip_reference.py")
  @vectors Path.join(__DIR__, "vectors/gossip_wire_v1.json")

  setup do
    v = Jason.decode!(File.read!(@vectors))
    dir = temp()

    make = fn actor, directory ->
      {:ok, store} = Store.start_link(directory: directory)

      Gossip.config!(FederationService.config!(actor: actor, private_key: nil, store: store),
        scope: v["scope"],
        publisher_keys: v["pins"],
        seed: Base.decode16!(v["test_seeds"][actor], case: :lower),
        require_freshness_lease: true
      )
    end

    a = make.(@alpha, dir <> "/a")
    b = make.(@beta, dir <> "/b")

    on_exit(fn ->
      stop_store(a.service.store)
      stop_store(b.service.store)
      File.rm_rf!(dir)
    end)

    %{
      v: v,
      a: a,
      b: b,
      dir: dir,
      now: v["now"],
      messages: Map.new(v["messages"], &{&1["name"], &1})
    }
  end

  defp hash(bytes), do: :crypto.hash(:sha256, bytes) |> Base.encode16(case: :lower)
  defp message(c, name), do: Jason.decode!(c.messages[name]["wire"])

  defp payload(c) do
    c |> message("create") |> Map.fetch!("payload") |> Base.decode64!() |> Jason.decode!()
  end

  defp publish(c) do
    p = payload(c)

    assert {:ok, :published} =
             Store.call(
               c.a.service.store,
               {:publish, "wire-test-source", p["activity"], p["metadata"], [], c.now}
             )

    p["activity"]["id"]
  end

  defp python(bundle, dir) do
    file = dir <> "/bundle.json"
    File.write!(file, Jason.encode!(bundle))
    {output, code} = System.cmd("python3", [@reference, "verify", file], stderr_to_stdout: true)
    assert code == 0, output
    assert output =~ "wire signatures and commitments verified"
  end

  test "canonical bytes, content hashes and topic match independent fixed vectors", c do
    assert c.v["test_only"]
    assert Gossip.topic(c.a) == c.v["topic"]

    for vector <- c.v["canonical"] do
      bytes = GossipSync.canonical(vector["value"])
      assert Base.encode16(bytes, case: :lower) == vector["hex"]
      assert hash(bytes) == vector["sha256"]
    end

    for name <- ~w(create update delete) do
      {:ok, _, activity, metadata, _} = Gossip.decode(c.b, c.messages[name]["wire"])
      assert GossipSync.content_hash(activity, metadata) == c.messages[name]["content_hash"]
    end

    for name <- ~w(lease offer receipt) do
      bytes = message(c, name) |> Map.delete("signature") |> GossipSync.canonical()
      assert Base.encode16(bytes, case: :lower) == c.messages[name]["transcript_hex"]
    end
  end

  test "externally signed advertisements, lease and offer pass real receiver admission", c do
    assert {:ok, :queued} = Gossip.receive_event(c.b, c.messages["create"]["wire"], c.now)
    Gossip.drain(c.b, c.now)
    assert [%{stale: true}] = FederationService.search(c.b.service, "", c.now)
    # Outer whitespace/order/Unicode escaping is not part of the control signature.
    lease = Jason.encode!(message(c, "lease"), pretty: true, escape: :unicode_safe)
    assert {:ok, :accepted} = GossipLease.receive_event(c.b, lease, c.now)

    assert [%{stale: false, freshness_source: "publisher_lease"}] =
             FederationService.search(c.b.service, "", c.now)

    assert :ok = GossipSync.receive_event(c.b, c.messages["offer"]["wire"], c.now)
    GossipSync.drain(c.b, c.now)
    assert [{_, receipt}] = GossipSync.frames(c.b, c.now, MapSet.new())
    # This receipt is generated by the actual durable receiver, not a fixture stub.
    python(Map.put(c.v, "messages", [%{"actor" => @beta, "wire" => receipt}]), c.dir)
    assert {:ok, :queued} = Gossip.receive_event(c.b, c.messages["update"]["wire"], c.now + 1)
    Gossip.drain(c.b, c.now + 1)

    assert [%{stale: true, metadata: %{"revision" => 1}}] =
             FederationService.search(c.b.service, "", c.now + 1)

    assert {:ok, :queued} = Gossip.receive_event(c.b, c.messages["delete"]["wire"], c.now + 2)
    Gossip.drain(c.b, c.now + 2)
    assert FederationService.search(c.b.service, "", c.now + 2) == []
    assert Store.call(c.b.service.store, :snapshot).events == %{}
  end

  test "external receipt requires a matching durable outgoing manifest", c do
    publish(c)
    raw = c.messages["receipt"]["wire"]
    assert {:error, :catchup_refused} = GossipSync.receive_event(c.a, raw, c.now)
    m = message(c, "offer") |> Map.drop(~w(signature announcement))
    key = "sync:" <> hash(GossipSync.canonical(Map.take(m, ~w(kind from to round))))
    row = %{message: m, peer_key: c.v["pins"][@beta], status: :pending, last_sent: nil}
    # Fixture setup installs the exact known manifest; normal start_round uses a random nonce.
    assert :ok = Store.call(c.a.service.store, {:sync_put, :sync_outgoing, key, row})
    assert :ok = GossipSync.receive_event(c.a, raw, c.now)
    assert {:ok, %{state: :complete, current: true}} = GossipSync.status(c.a, m["round"], c.now)
  end

  test "independent verifier accepts live Elixir publisher and durable receiver frames", c do
    id = publish(c)
    [{_, ad}] = Gossip.frames(c.a, c.now)
    assert {:ok, :queued} = Gossip.receive_event(c.b, ad, c.now)
    Gossip.drain(c.b, c.now)
    assert {:ok, _} = GossipLease.renew(c.a, id, 300, c.now)
    [{_, lease}] = GossipLease.frames(c.a, c.now, MapSet.new())
    assert {:ok, round} = GossipSync.start_round(c.a, @beta, [id], c.now)
    [{_, offer}] = GossipSync.frames(c.a, c.now, MapSet.new())
    assert :ok = GossipSync.receive_event(c.b, offer, c.now)
    GossipSync.drain(c.b, c.now)
    [{_, receipt}] = GossipSync.frames(c.b, c.now, MapSet.new())

    frames =
      for {actor, wire} <- [{@alpha, ad}, {@alpha, lease}, {@alpha, offer}, {@beta, receipt}] do
        %{
          "actor" => actor,
          "wire" => wire,
          "content_hash" => c.messages["create"]["content_hash"]
        }
      end

    python(Map.put(c.v, "messages", frames), c.dir)
    assert :ok = GossipSync.receive_event(c.a, receipt, c.now)
    assert {:ok, %{state: :complete}} = GossipSync.status(c.a, round, c.now)
    assert map_size(Store.call(c.a.service.store, :snapshot).events) == 1
    assert Store.call(c.b.service.store, :snapshot).events == %{}
  end
end
